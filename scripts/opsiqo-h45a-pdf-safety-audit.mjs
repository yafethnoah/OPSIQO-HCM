import { readFileSync, existsSync } from 'node:fs';
const read=(p)=>readFileSync(p,'utf8');
const service=read('src/lib/recruiting/ats-service.ts');
const ui=read('src/components/resume-intake-assistant.tsx');
const identity=read('src/lib/release/identity.ts');
const readiness=read('src/components/recruiting-readiness-panel.tsx');
const checks=[];
const add=(name,ok)=>{checks.push({name,ok});console.log(`${ok?'PASS':'FAIL'}  ${name}`)};
add('PDF text layer state distinguishes absent from unsafe', service.includes('pdfTextLayerState') && service.includes('"absent" | "unsafe"'));
add('unsafe PDF text remains resume_parser_unavailable', service.includes('pdfLayerState === "unsafe"') && service.includes('"resume_parser_unavailable"'));
add('empty/scanned PDF retains Recruiting AI setup guidance', service.includes('"recruiting_ai_setup_required"'));
add('candidate fields remain fail-closed for unsafe PDF', service.includes('No candidate fields were accepted'));
add('resume UI maps unsafe PDF to user-safe guidance', ui.includes('e.code === "resume_parser_unavailable"') && ui.includes('could not be read safely'));
add('H45A patch identity is explicit', identity.includes("OPSIQO_PATCH_RELEASE") && identity.includes("'H45A'"));
add('recruiting readiness displays patch identity', readiness.includes('patchRelease'));
add('H45A regression test exists', existsSync('tests/recruiting-pdf-classification-h45a.test.ts'));
const failed=checks.filter(c=>!c.ok);
console.log(`\nH45A audit: ${checks.length-failed.length}/${checks.length} PASS`);
if(failed.length)process.exit(1);
