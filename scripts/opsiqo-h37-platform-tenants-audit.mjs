import fs from 'node:fs';
const checks=[];
const text=file=>fs.readFileSync(file,'utf8');
const check=(name,ok)=>{checks.push({name,ok:Boolean(ok)});console.log(`${ok?'PASS':'FAIL'}  ${name}`)};
const service=text('src/lib/platform/tenant-management.ts');
const route=text('src/app/api/platform/tenants/route.ts');
const page=text('src/components/platform-tenant-workspace.tsx');
const nav=text('src/components/nav.tsx');
check('Tenant service requires super_admin role',service.includes("actor.role !== 'super_admin'")&&service.includes('super_admin_required'));
check('Tenant creation requires a verified identity',service.includes('OPSIQO_PLATFORM_REQUIRE_VERIFIED_EMAIL')&&service.includes('verified_email_required'));
check('Tenant input requires a documented reason',service.includes('reason: z.string().trim().min(10).max(500)'));
check('Tenant names have a transactional uniqueness claim',service.includes('_platformOrganizationNames')&&service.includes('nameClaim.exists'));
check('Tenant foundation is created transactionally',service.includes('db.runTransaction')&&service.includes('tx.create(orgRef'));
check('New tenant receives isolated super-admin membership',service.includes("role:'super_admin'")&&service.includes('/memberships/'));
check('Tenant creation writes authoritative audit evidence',service.includes("action:'platform.tenant.create'")&&service.includes('/auditLogs/'));
check('Tenant API supports governed list and create',route.includes('export async function GET')&&route.includes('export async function POST'));
check('Platform Companies screen exists',fs.existsSync('src/app/platform-tenants/page.tsx')&&page.includes('Create a separate company'));
check('UI makes cross-tenant isolation explicit',page.includes('No data is copied from the current organization'));
check('Navigation is restricted to super_admin',nav.includes("href:'/platform-tenants'")&&nav.includes("roles:['super_admin']"));
check('Targeted H37 tests exist',fs.existsSync('tests/platform-tenant-management.test.ts'));
const failed=checks.filter(c=>!c.ok);
console.log(`\nH37 PLATFORM TENANT CREATION AUDIT: ${checks.length-failed.length}/${checks.length} PASS`);
if(failed.length)process.exitCode=1;
