import fs from 'node:fs';
const read = p => fs.readFileSync(p, 'utf8');
const identity = read('src/lib/release/identity.ts');
const pkg = JSON.parse(read('mobile/package.json'));
const app = JSON.parse(read('mobile/app.json'));
const eas = JSON.parse(read('mobile/eas.json'));
const freeze = read('FREEZE_OPSIQO_H47_1F_MOBILE_LOCK.ps1');
const validate = read('RUN_OPSIQO_H47_1F_VALIDATION.ps1');
const priorTest = read('tests/mobile-employee-h47-1e.test.ts');
const priorAudit = read('scripts/opsiqo-h47-1e-expo-doctor-isolation-audit.mjs');
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
add('H47.1F patch identity is explicit', identity.includes("OPSIQO_PATCH_RELEASE = process.env.OPSIQO_PATCH_RELEASE || 'H47.1F'"));
add('employee mobile package advances to 0.2.5', pkg.version === '0.2.5');
add('native marketing version advances to 0.1.2', app.expo?.version === '0.1.2');
add('mobile release marker advances to employee-mobile-v1.1f', app.expo?.extra?.h47Release === 'employee-mobile-v1.1f');
add('iOS build number seed is explicit', app.expo?.ios?.buildNumber === '1');
add('Android version code seed is explicit', app.expo?.android?.versionCode === 1);
add('EAS uses remote app version source', eas.cli?.appVersionSource === 'remote');
add('UAT build uses internal distribution and uat channel', eas.build?.uat?.distribution === 'internal' && eas.build?.uat?.channel === 'uat');
add('UAT build is bound to EAS preview environment', eas.build?.uat?.environment === 'preview');
add('UAT API base is explicitly isolated', eas.build?.uat?.env?.EXPO_PUBLIC_OPSIQO_API_BASE_URL === 'https://uat.opsiqo.ca');
add('production build is bound to EAS production environment', eas.build?.production?.environment === 'production');
add('production API URL is not hardcoded into eas.json', !Object.hasOwn(eas.build?.production?.env || {}, 'EXPO_PUBLIC_OPSIQO_API_BASE_URL'));
add('UAT and production auto-increment build identifiers', eas.build?.uat?.autoIncrement === true && eas.build?.production?.autoIncrement === true);
add('freeze script generates package lock only from package metadata', freeze.includes('npm install --package-lock-only') && freeze.includes('--ignore-scripts'));
add('freeze script invokes the full npm-ci final validator', freeze.includes('RUN_OPSIQO_H47_1F_VALIDATION.ps1'));
add('final validator requires committed mobile package lock', validate.includes("'package-lock.json'") && validate.includes('Frozen mobile package-lock.json is missing'));
add('final validator uses npm ci rather than npm install for mobile', validate.includes('npm ci --no-audit --no-fund') && !validate.includes('npm install --no-audit --no-fund'));
add('H47.1E historical test accepts successor patches', priorTest.includes('H47.1E-or-later') && priorTest.includes('[E-Z]'));
add('H47.1E historical audit accepts successor patches', priorAudit.includes('H47.1E-or-later') && priorAudit.includes('[E-Z]'));
let pass=0; for(const c of checks){console.log(`${c.ok?'PASS':'FAIL'}  ${c.name}`); if(c.ok)pass++;}
console.log(`\nH47.1F lock-capture audit: ${pass}/${checks.length} PASS`);
if(pass!==checks.length) process.exit(1);
